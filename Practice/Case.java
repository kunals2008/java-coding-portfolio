class Case
{
	public static void main(String[] args)
	{
		int i = 8;
		switch(i)
		{
			case 2:
			  System.out.println("I am case 2");
			  break;
			case 4:
			  System.out.println("I am case 4");
			  break;
			case 6:
			 System.out.println("I am case 6");
			 break;
			 default:
			 System.out.println("im value " + i);
			 break;
			 
		}
	}
}
		